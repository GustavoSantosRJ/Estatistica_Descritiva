-- =============================================================================
-- CRIAÇÃO DA BASE E ESTRUTURA DAS TABELAS
-- =============================================================================
CREATE DATABASE IF NOT EXISTS analise_vendas;
USE analise_vendas;

DROP TABLE IF EXISTS vendas;
DROP TABLE IF EXISTS produtos;
DROP TABLE IF EXISTS clientes;

-- 1. Tabela Dimensional: Clientes (60 registros)
CREATE TABLE clientes (
    id_cliente INT AUTO_INCREMENT PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    cidade VARCHAR(60) NOT NULL,
    estado CHAR(2) NOT NULL,
    segmento VARCHAR(30) NOT NULL,
    data_cadastro DATE NOT NULL
);

-- 2. Tabela Dimensional: Produtos (50 registros)
CREATE TABLE produtos (
    id_produto INT AUTO_INCREMENT PRIMARY KEY,
    nome_produto VARCHAR(100) NOT NULL,
    categoria VARCHAR(50) NOT NULL,
    subcategoria VARCHAR(50) NOT NULL,
    custo_unitario DECIMAL(10,2) NOT NULL,
    preco_unitario DECIMAL(10,2) NOT NULL
);

-- 3. Tabela Fato / Transacional: Vendas (200 registros)
CREATE TABLE vendas (
    id_venda INT AUTO_INCREMENT PRIMARY KEY,
    id_cliente INT NOT NULL,
    id_produto INT NOT NULL,
    data_venda DATE NOT NULL,
    quantidade INT NOT NULL,
    desconto_percentual DECIMAL(5,2) DEFAULT 0.00,
    canal_venda VARCHAR(30) NOT NULL,
    FOREIGN KEY (id_cliente) REFERENCES clientes(id_cliente),
    FOREIGN KEY (id_produto) REFERENCES produtos(id_produto)
);

